import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { LEADERSHIP_ROLES, roleTargets, parseRoleSource, adaptRoleBody } from './roles-generation.mjs';
const root = process.cwd();
const inventory = JSON.parse(readFileSync('docs/codex/upstream-inventory.json', 'utf8'));
const roles = inventory.files.filter(f => f.category === 'agent').map(f => f.path.split('/').at(-1).replace(/\.md$/, ''));
const names = roles.filter(n => !LEADERSHIP_ROLES.includes(n) && !/^(godot-|unity-|unreal-|ue-)/.test(n));
const skillNames = inventory.files.filter(f => /^\.claude\/skills\/[^/]+\/SKILL\.md$/.test(f.path)).map(f => f.path.split('/')[2]);
assert.equal(roles.length, 49); assert.equal(names.length, 23);
assert.throws(() => parseRoleSource('---\nname: test\ndescription: test\ntools: Read\nisolation: unknown\n---\n', 'fixture'), /Unsupported source isolation/);
for (const p of roleTargets(root, names)) {
  const name = p.target.split('/').at(-1).replace(/\.toml$/, '');
  assert.equal(p.owner, 'CGS-08');
  const source = readFileSync(p.source, 'utf8').replace(/\r\n?/g, '\n');
  const { fields, body } = parseRoleSource(source, p.source);
  const target = p.content.toString('utf8');
  const instruction = JSON.parse(target.match(/^developer_instructions = (".*")$/m)[1]);
  const adapted = adaptRoleBody(body, skillNames).body;
  assert.equal(instruction.split('## Adapted source role\n\n')[1], adapted, `${name}: source body differs beyond declared transforms`);
  assert.ok(instruction.includes('in-session role review; not independent'));
  assert.ok(instruction.includes('Prior user authorization persists'));
  assert.doesNotMatch(target, /^model\s*=/m);
  assert.doesNotMatch(instruction, /CLAUDE_PROJECT_DIR|CLAUDE_SKILL_DIR|AskUserQuestion/);
  if (fields.disallowedTools?.split(/,\s*/).includes('Bash')) assert.match(target, /\[features\]\nshell_tool = false/);
  if (fields.memory) assert.ok(instruction.includes(`.agents/agent-memory/${name}/`));
  if (fields.isolation) assert.match(instruction, /worktree isolation[\s\S]*Do not claim/);
  if (!process.argv.includes('--plans')) { assert.ok(existsSync(p.target), `Missing generated ${p.target}`); assert.ok(readFileSync(p.target).equals(p.content), `Generated bytes differ: ${p.target}`); }
}
for (const p of roleTargets(root, LEADERSHIP_ROLES)) assert.ok(readFileSync(p.target).equals(p.content), `Leadership output changed: ${p.target}`);
const fixture = 'docs/codex/evidence/CGS-08/fixtures/';
const files = ['gameplay.js', 'design.md', 'gameplay.test.js'];
const digest = f => createHash('sha256').update(readFileSync(fixture + f)).digest('hex');
const before = files.map(digest);
const zero = spawnSync(process.execPath, ['--experimental-default-type=module', fixture + 'gameplay.test.js'], { encoding: 'utf8' });
assert.equal(zero.status, 0, zero.stderr);
const probe = spawnSync(process.execPath, ['--experimental-default-type=module', '-e', `import {applyDamage} from './${fixture}gameplay.js'; console.log(JSON.stringify([applyDamage(100,10),applyDamage(5,10),applyDamage(80,-10)]))`], { encoding: 'utf8' });
assert.equal(probe.status, 0, probe.stderr); assert.deepEqual(JSON.parse(probe.stdout), [80, -15, 100]);
assert.deepEqual(files.map(digest), before, 'fixture changed during checks');
console.log(`PASS: 23 specialist ${process.argv.includes('--plans') ? 'plans' : 'targets'}, exact adapted bodies, permissions, no model pins, memory, isolation, and 11 unchanged leadership targets.`);
